-- ============================================================
-- Migration 054: 相談チャットから紹介リストを送れるようにする
-- ============================================================
--
-- CEO決定（2026-08-06・重要な方針転換）:
-- 「代理案内とか代替リストをフロントで出しちゃうと、そもそも紹介につながらない！！
--   フロントで代替リストボタンを出せるのは団体オーナーだけにして、あとは出せなくする。
--   そんで、相談チャットからワンクリックで自分の紹介リストを送れるようにする。」
--
-- 何が問題だったか:
--   公開カードに候補一覧を出すと、クライアントはそこから勝手に選ぶ。
--   その結果「誰の紹介でもない」着地になり、**紹介の実体も記録も残らない**。
--   紹介機能そのものが死ぬ。
--
-- どう変えるか:
--   ・公開カードに一覧を出せるのは団体オーナーだけ（§16-34）
--   ・それ以外のプロは、相談チャットから自分の紹介リストを送る（§16-35）
--     こちらは「◯◯さんが紹介した」という実体が残る＝ちゃんと紹介になる
--
-- menu_id（052）と同じ作り。body に人が読む文を必ず入れるので、
-- このカラムが無い環境でも会話としては成立する（fail-soft）。
-- ============================================================

ALTER TABLE consultation_messages
  ADD COLUMN IF NOT EXISTS list_id uuid REFERENCES referral_lists(id) ON DELETE SET NULL;

COMMENT ON COLUMN consultation_messages.list_id IS
  'プロが相談チャットで送った紹介リスト。null なら通常のメッセージ。紹介の実体をここに残す（§16-35）。';

